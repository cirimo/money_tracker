package dev.cirimo.trosko.designsystem.component

/**
 * A second ink outline drawn just outside a sticker. It says something about the sticker that
 * its fill must not be trusted to say alone.
 */
enum class SecondOutline {
    /** The sticker is the chosen one of a group. */
    Solid,

    /** The sticker has keyboard focus. */
    Dashed,
}
